"""Q-learning informed traders in the low-noise regime of Dou, Goldstein and Ji,
where they report trigger strategies: the rival's response to a forced deviation,
pooled over seeds, forward-looking (gamma 0.95) against myopic (gamma 0) learners.
Writes results/dou_lownoise.json and paper/numbers_dou.tex.

    python experiments/dou_lownoise.py
"""
from __future__ import annotations

import glob
import json
import os

import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def pool(g: str) -> dict:
    fs = (sorted(glob.glob(os.path.join(ROOT, f"results/exp16_dou_faithful/price_{g}_lownoise.json")))
          + sorted(glob.glob(os.path.join(ROOT, f"results/exp17_dou_lownoise_seeds/price_{g}_lownoise_s*.json"))))
    rs, cs, ds, gs, gc, pis = [], [], [], [], [], []
    for f in fs:
        r = json.load(open(f))
        imp = r["impulse"]
        rs.append(imp["d_beta_rival"][1])
        cs.append(imp["d_beta_rival_ci95"][1])
        ds.append(imp["d_beta_dev"][0])
        gs.append(imp["cum_gain_dev"])
        gc.append(imp["cum_gain_dev_ci95"])
        pis.append(float(np.mean(r["per_session"]["delta_profit"])))
        nash = r["benchmarks"]["profit_nash"]
    w = 1 / (np.asarray(cs) / 1.96) ** 2
    m = float((w * np.asarray(rs)).sum() / w.sum())
    gw = 1 / (np.asarray(gc) / 1.96) ** 2
    return {"seeds": len(fs), "rival": m, "rival_ci95": float(1.96 / np.sqrt(w.sum())),
            "per_unit": m / float(np.mean(ds)), "n_positive": int(sum(x > 0 for x in rs)),
            "n_significant": int(sum(x - c > 0 for x, c in zip(rs, cs))),
            "gain": float((gw * np.asarray(gs)).sum() / gw.sum()), "gain_ci95": float(1.96 / np.sqrt(gw.sum())),
            "profit_index": float(np.mean(pis)), "nash_profit": float(nash)}


def main():
    out = {"forward": pool("g095"), "myopic": pool("g0")}
    json.dump(out, open(os.path.join(ROOT, "results", "dou_lownoise.json"), "w"), indent=1)
    f, m = out["forward"], out["myopic"]
    macros = {"LowNoiseSeeds": f["seeds"], "LowNoiseRival": f"{f['rival']:.2f}", "LowNoiseRivalCI": f"{f['rival_ci95']:.2f}",
              "LowNoisePerUnit": f"{f['per_unit']:.2f}", "LowNoiseGain": f"{f['gain']:.2f}", "LowNoiseGainCI": f"{f['gain_ci95']:.2f}",
              "LowNoiseProfit": f"{f['profit_index']:.2f}", "LowNoisePos": f["n_positive"],
              "LowNoiseSig": f["n_significant"], "LowNoiseNashProfit": f"{f['nash_profit']:.1f}",
              "LowNoiseGainPct": f"{100 * f['gain'] / f['nash_profit']:.0f}",
              "LowNoiseMyopicRival": f"{m['rival']:.2f}", "LowNoiseMyopicRivalCI": f"{m['rival_ci95']:.2f}"}
    with open(os.path.join(ROOT, "paper", "numbers_dou.tex"), "w") as fh:
        fh.write("% generated by experiments/dou_lownoise.py\n")
        for k, v in macros.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
