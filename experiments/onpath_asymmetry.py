"""On-path asymmetry under the protocol of Fish et al.: does a firm follow its rival's price cuts more
than its rises? Regresses each firm's price change on the positive and negative parts of the rival's
change one period earlier, with session fixed effects and standard errors clustered by session (the
symmetric-deviation idea of Epivent and Lambin, 2024, applied to observed play). Punishment predicts
following cuts more than rises; imitation or best responses predict both alike.
Writes results/onpath_asymmetry.json and paper/numbers_asym.tex.

    python experiments/onpath_asymmetry.py
"""
from __future__ import annotations

import json
import os

import numpy as np
from scipy import stats

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RUNS = {"gpt52_high_duopoly_P1": "GptFive", "gpt52_high_myopic_P1": "GptFiveMyo",
        "gptoss20b_duopoly_P1": "Oss", "gptoss120b_duopoly_P1": "OssBig",
        "gptoss20b_high32k_duopoly_P1": "OssHigh"}
BURN = 10  # periods of initial price discovery left out


def fit(path):
    d = json.load(open(path))
    P = np.asarray(d["prices_sessions"], float)  # sessions x periods x firms
    span = d["bench"]["p_mono"] - d["bench"]["p_nash"]
    rows = []
    for s in range(P.shape[0]):
        for i in (0, 1):
            own, riv = np.diff(P[s, :, i]) / span, np.diff(P[s, :, 1 - i]) / span
            for t in range(BURN, len(own) - 1):
                rows.append((s, own[t + 1], max(riv[t], 0.0), min(riv[t], 0.0)))
    R = np.array(rows)
    S = R[:, 0].astype(int)
    Y, X = R[:, 1].copy(), R[:, 2:].copy()
    for s in np.unique(S):  # session fixed effects
        m = S == s
        Y[m] -= Y[m].mean()
        X[m] -= X[m].mean(0)
    beta = np.linalg.lstsq(X, Y, rcond=None)[0]
    e = Y - X @ beta
    XtX = np.linalg.inv(X.T @ X)
    meat = sum(np.outer(X[S == s].T @ e[S == s], X[S == s].T @ e[S == s]) for s in np.unique(S))
    G = len(np.unique(S))
    V = XtX @ meat @ XtX * G / (G - 1)
    tq = stats.t.ppf(0.975, G - 1)
    c = np.array([-1.0, 1.0])
    return {"rises": (float(beta[0]), float(tq * np.sqrt(V[0, 0]))),
            "cuts": (float(beta[1]), float(tq * np.sqrt(V[1, 1]))),
            "cuts_minus_rises": (float(c @ beta), float(tq * np.sqrt(c @ V @ c))),
            "sessions": G, "n_rises": int((R[:, 2] > 1e-9).sum()), "n_cuts": int((R[:, 3] < -1e-9).sum())}


def main():
    out, macros = {}, {}
    for run, key in RUNS.items():
        f = os.path.join(ROOT, "results", "llm_fish", f"{run}.json")
        if not os.path.exists(f):
            continue
        r = out[run] = fit(f)
        for k, nm in (("rises", "Rise"), ("cuts", "Cut"), ("cuts_minus_rises", "Diff")):
            macros[f"Asym{key}{nm}"] = f"{r[k][0]:.2f}\\pm{r[k][1]:.2f}"
        print(run, r)
    json.dump(out, open(os.path.join(ROOT, "results", "onpath_asymmetry.json"), "w"), indent=1)
    with open(os.path.join(ROOT, "paper", "numbers_asym.tex"), "w") as fh:
        fh.write("% generated by experiments/onpath_asymmetry.py -- do not edit\n")
        for k, v in macros.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


if __name__ == "__main__":
    main()
