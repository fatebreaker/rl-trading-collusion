"""Depth test with the market maker's rule disclosed: elasticity of a lone
trader's intensity with depth, with and without the rule in the prompt.
Writes results/disclose_summary.json and paper/numbers_disclose.tex.

    python experiments/disclose_summary.py
"""
from __future__ import annotations

import json
import os

import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
MODELS = {"mistral7b": ("Mistral", "llm_models/mistral7b_solo_su{}.json"),
          "qwen3_8b": ("Qwen", "llm_pilot/qwen3_8b_solo_su{}.json")}


def intensity(path):
    f = os.path.join(ROOT, "results", path)
    if not os.path.exists(f):
        return None
    return float(json.load(open(f))["summary"]["agg_intensity"]["mean"])


def elasticity(lo, hi):
    return None if lo is None or hi is None else float(np.log(hi / lo) / np.log(4))


def main():
    out, macros = {}, {}
    for tag, (name, base) in MODELS.items():
        d = [intensity(f"llm_disclose/{tag}_solo_su{s}.json") for s in ("0.5", "2")]
        u = [intensity(base.format(s)) for s in ("0.5", "2")]
        if tag == "qwen3_8b" and u[0] is None:  # the base Qwen3-8B solo runs at s=0.5 are named differently
            u = [intensity("llm_pilot/qwen3_8b_solo_su0.5.json") or intensity("llm_pilot/qwen3_8b_solo.json"),
                 intensity("llm_pilot/qwen3_8b_solo_su2.json")]
        out[tag] = {"disclosed": d, "undisclosed": u, "elast_disclosed": elasticity(*d),
                    "elast_undisclosed": elasticity(*u)}
        for k, v in (("Disc", elasticity(*d)), ("Undisc", elasticity(*u))):
            macros[f"Elast{k}{name}"] = "--" if v is None else f"{v:.2f}"
        macros[f"DiscLow{name}"] = "--" if d[0] is None else f"{d[0]:.2f}"
        macros[f"DiscHigh{name}"] = "--" if d[1] is None else f"{d[1]:.2f}"
    json.dump(out, open(os.path.join(ROOT, "results", "disclose_summary.json"), "w"), indent=1)
    os.makedirs(os.path.join(ROOT, "paper"), exist_ok=True)
    with open(os.path.join(ROOT, "paper", "numbers_disclose.tex"), "w") as fh:
        fh.write("% generated by experiments/disclose_summary.py\n")
        for k, v in macros.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
