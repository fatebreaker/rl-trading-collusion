"""Escalation of trading when Qwen3-8B traders see each other's orders: per-session
slope of aggregate intensity across 20-period blocks (intensity per 100 periods),
with and without the rival's orders shown, two seeds each. Writes
results/escalation_summary.json and paper/numbers_escalation.tex.

    python experiments/escalation_summary.py
"""
from __future__ import annotations

import json
import os
import sys

import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "experiments"))
from llm_tabulate import escalation  # noqa: E402

PAIRS = [("llm_pilot/qwen3_8b_monitor_s1.json", "llm_pilot/qwen3_8b_duopoly_s1.json"),
         ("llm_pilot/qwen3_8b_monitor_s2.json", "llm_pilot/qwen3_8b_duopoly_s2.json")]


def main():
    rows = []
    for mon, duo in PAIRS:
        (m1, c1), (m0, c0) = (escalation(json.load(open(os.path.join(ROOT, "results", f)))) for f in (mon, duo))
        rows.append({"monitor": (m1, c1), "duopoly": (m0, c0), "diff": (m1 - m0, float(np.hypot(c1, c0)))})
    w = np.array([1 / r["diff"][1] ** 2 for r in rows])
    d = float((w * np.array([r["diff"][0] for r in rows])).sum() / w.sum())
    dc = float(1.96 / np.sqrt((w * 1.96 ** 2).sum()))
    out = {"seeds": rows, "pooled_diff": (d, dc)}
    json.dump(out, open(os.path.join(ROOT, "results", "escalation_summary.json"), "w"), indent=1)
    macros = {"EscDiff": f"{d:.2f}", "EscDiffCI": f"{dc:.2f}",
              "EscMonLow": f"{min(r['monitor'][0] for r in rows):.2f}", "EscMonHigh": f"{max(r['monitor'][0] for r in rows):.2f}",
              "EscDuoLow": f"{min(r['duopoly'][0] for r in rows):.2f}", "EscDuoHigh": f"{max(r['duopoly'][0] for r in rows):.2f}"}
    with open(os.path.join(ROOT, "paper", "numbers_escalation.tex"), "w") as fh:
        fh.write("% generated by experiments/escalation_summary.py\n")
        for k, v in macros.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    print(json.dumps(out, indent=1), macros)


if __name__ == "__main__":
    main()
