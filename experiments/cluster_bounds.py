"""Worst-case session clustering for the trading deviation tests.

Deviation-test intervals are computed across events, several per session. Events of one session are
not independent; in the worst case they are identical, and the session means carry all the
information. The standard error then grows by sqrt(events / sessions). This script applies that
inflation to every test in results/deviation_tests.csv (written by null_bounds.py) and reports which
responses stay significant, the median minimum detectable effect (80% power) of the tests with the
rival's orders shown, and the bounds of the instructed positive controls.
Writes paper/numbers_cluster.tex and results/cluster_bounds.json.
"""

from __future__ import annotations

import csv
import json
import os

import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def sessions(path: str) -> int:
    d = json.load(open(os.path.join(ROOT, "results", path)))
    return int(d["args"]["sessions"])


def main():
    rows = list(csv.DictReader(open(os.path.join(ROOT, "results", "deviation_tests.csv"))))
    out = []
    for r in rows:
        n, m, ci = int(r["n"]), float(r["mean"]), float(r["ci"])
        S = sessions(r["file"])
        k = float(np.sqrt(max(n / S, 1.0)))  # worst case: every event of a session identical
        out.append({**r, "sessions": S, "inflation": k, "ci_cluster": ci * k,
                    "sig": bool(m - ci > 0), "sig_cluster": bool(m - ci * k > 0)})
    null = [o for o in out if o["control"] == "False"]
    ctrl = [o for o in out if o["control"] == "True"]
    mon_br = [o for o in null if o["structure"] == "monitor" and o["test"] == "deviation"
              and float(o["ci"]) / 1.96 > 0.001]
    mde = float(np.median([2.8 * o["ci_cluster"] / 1.96 for o in mon_br]))
    res = {"n_null": len(null), "sig_null": int(sum(o["sig"] for o in null)),
           "sig_null_cluster": int(sum(o["sig_cluster"] for o in null)),
           "median_mde80_monitor_br_cluster": mde,
           "max_inflation": max(o["inflation"] for o in out),
           "controls": [{k: o[k] for k in ("file", "test", "mean", "ci", "ci_cluster", "sig", "sig_cluster")}
                        for o in ctrl]}
    json.dump(res, open(os.path.join(ROOT, "results", "cluster_bounds.json"), "w"), indent=1)
    sig_ctrl = [o for o in ctrl if o["sig"]]
    lows = [float(o["mean"]) - o["ci_cluster"] for o in sig_ctrl]
    macros = {"ClustNullSig": res["sig_null_cluster"], "ClustMonBRMDE": f"{mde:.2f}",
              "ClustMaxInfl": f"{res['max_inflation']:.1f}",
              "ClustCtrlSig": sum(o["sig_cluster"] for o in sig_ctrl), "ClustCtrlN": len(sig_ctrl),
              "ClustCtrlLowMin": f"{min(lows):.2f}" if lows else "--"}
    with open(os.path.join(ROOT, "paper", "numbers_cluster.tex"), "w") as fh:
        fh.write("% generated by experiments/cluster_bounds.py -- do not edit\n")
        for k, v in macros.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    print(json.dumps({k: v for k, v in res.items() if k != "controls"}, indent=1))
    for o in ctrl:
        print(f"{o['file']:45s} {o['test']:16s} {float(o['mean']):+.3f} +- {float(o['ci']):.3f} -> +- {o['ci_cluster']:.3f}"
              f"  sig {o['sig']} -> {o['sig_cluster']}")
    print(macros)


if __name__ == "__main__":
    main()
