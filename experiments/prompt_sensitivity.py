"""Depth-blindness under different prompt wordings.

For each model without reasoning and each system-prompt wording (a: original,
b: paraphrase, c: market-microstructure register, d: terse), the intensity of a
lone trader at sigma_u = 0.5 and 2 (optima 0.5 and 2) and its elasticity with
depth (1 for a trader that understands price impact).

Writes results/prompt_sensitivity.json, paper/table_prompts.tex and
paper/numbers_prompts.tex.
"""
from __future__ import annotations

import json
import math
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORDING = {"a": "original", "b": "paraphrase", "c": "finance register", "d": "terse",
           "g": "original, greedy decoding", "r": "original, price rule stated"}
RUNS = {  # model -> wording -> (file at s=0.5, file at s=2), without .json
    "Qwen3-8B": {"a": ("llm_pilot/qwen3_8b_solo_su0.5", "llm_pilot/qwen3_8b_solo_su2"),
                 "b": ("llm_pilot/qwen3_8b_pb_solo_su0.5", "llm_pilot/qwen3_8b_pb_solo_su2"),
                 "c": ("llm_prompts/qwen3_8b_c_solo_su0.5", "llm_prompts/qwen3_8b_c_solo_su2"),
                 "d": ("llm_prompts/qwen3_8b_d_solo_su0.5", "llm_prompts/qwen3_8b_d_solo_su2"),
                 "g": ("llm_prompts/qwen3_8b_greedy_solo_su0.5", "llm_prompts/qwen3_8b_greedy_solo_su2"),
                 "r": ("llm_disclose/qwen3_8b_solo_su0.5", "llm_disclose/qwen3_8b_solo_su2")},
    "Qwen3-32B": {"a": ("llm_models/qwen3_32b_solo_su0.5", "llm_models/qwen3_32b_solo_su2"),
                  "c": ("llm_prompts/qwen3_32b_c_solo_su0.5", "llm_prompts/qwen3_32b_c_solo_su2"),
                  "d": ("llm_prompts/qwen3_32b_d_solo_su0.5", "llm_prompts/qwen3_32b_d_solo_su2")},
    "Mistral-7B": {"a": ("llm_models/mistral7b_solo_su0.5", "llm_models/mistral7b_solo_su2"),
                   "c": ("llm_prompts/mistral7b_c_solo_su0.5", "llm_prompts/mistral7b_c_solo_su2"),
                   "d": ("llm_prompts/mistral7b_d_solo_su0.5", "llm_prompts/mistral7b_d_solo_su2"),
                   "r": ("llm_disclose/mistral7b_solo_su0.5", "llm_disclose/mistral7b_solo_su2")},
}


def intensity(path):
    p = os.path.join(ROOT, "results", path + ".json")
    if not os.path.exists(p):
        return None
    b = np.asarray(json.load(open(p))["per_session"]["agg_intensity"], float)
    return float(b.mean()), float(1.96 * b.std(ddof=1) / np.sqrt(len(b)))


def main():
    rows, el_all = [], []
    for model, ws in RUNS.items():
        for w, (f05, f2) in ws.items():
            lo, hi = intensity(f05), intensity(f2)
            el = (math.log(hi[0] / lo[0]) / math.log(4)) if lo and hi and lo[0] > 0 and hi[0] > 0 else None
            if el is not None:
                el_all.append(el)
            rows.append({"model": model, "wording": w, "low": lo, "high": hi, "elasticity": el})
    json.dump(rows, open(os.path.join(ROOT, "results", "prompt_sensitivity.json"), "w"), indent=1)
    f = lambda x: "--" if x is None else f"${x[0]:.2f}$"  # noqa: E731
    lines = ["\\begin{tabular}{llccc}", "\\toprule",
             "Model & Wording & $s=0.5$ & $s=2$ & Elast. \\\\", "\\midrule"]
    last = None
    for r in rows:
        if last and r["model"] != last:
            lines.append("\\midrule")
        el = "--" if r["elasticity"] is None else f"${r['elasticity']:.2f}$"
        name = r["model"] if r["model"] != last else ""
        lines.append(f"{name} & {WORDING[r['wording']]} & {f(r['low'])} & {f(r['high'])} & {el} \\\\")
        last = r["model"]
    lines += ["\\midrule", "Optimum & & $0.50$ & $2.00$ & $1.00$ \\\\", "\\bottomrule", "\\end{tabular}"]
    open(os.path.join(ROOT, "paper", "table_prompts.tex"), "w").write("\n".join(lines) + "\n")
    lows = [r["low"][0] for r in rows if r["low"]]
    macros = {"PromptRuns": sum(1 for r in rows if r["elasticity"] is not None),
              "PromptElastMax": f"{max(el_all):.2f}" if el_all else "--",
              "PromptElastMin": f"{min(el_all):.2f}" if el_all else "--",
              "PromptLowMin": f"{min(lows):.2f}", "PromptLowMax": f"{max(lows):.2f}"}
    with open(os.path.join(ROOT, "paper", "numbers_prompts.tex"), "w") as fh:
        fh.write("% generated by experiments/prompt_sensitivity.py -- do not edit\n")
        for k, v in macros.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    for r in rows:
        print(r["model"], r["wording"], r["low"], r["high"], r["elasticity"])
    print(macros)


if __name__ == "__main__":
    main()
