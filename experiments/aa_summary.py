"""A/A tests of the pairing: deviation tests without a deviation, on vLLM
(Qwen3-8B) and through the OpenAI API (GPT-5.4-nano, low reasoning effort).
Reports how often the two copies' rival orders are identical and the null
"response". Writes results/aa_summary.json and paper/numbers_aa.tex.

    python experiments/aa_summary.py
"""
from __future__ import annotations

import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RUNS = {"Vllm": "aa_test/qwen3_8b_duopoly_su1_aa.json", "Api": "aa_test/nano-snap_low_duopoly_su1_aa.json"}


def main():
    out, macros = {}, {}
    for key, path in RUNS.items():
        f = os.path.join(ROOT, "results", path)
        if not os.path.exists(f):
            continue
        t = json.load(open(f)).get("deviation_none")
        if not t:
            continue
        same = t["share_identical_rival"]
        r = {"n": t["n_events"], "identical_lag1": same[1], "identical_min": min(same[1:]),
             "identical_max": max(same[1:]), "null": t["d_beta_rival"][1], "null_ci95": t["d_beta_rival_ci95"][1]}
        out[key] = r
        macros[f"AA{key}SameLagOne"] = f"{100 * r['identical_lag1']:.0f}"
        macros[f"AA{key}SameMin"] = f"{100 * r['identical_min']:.0f}"
        macros[f"AA{key}SameMax"] = f"{100 * r['identical_max']:.0f}"
        m = r["null"]
        macros[f"AA{key}Null"] = f"{abs(m) if abs(m) < 5e-4 else m:.3f}"
        macros[f"AA{key}NullCI"] = f"{r['null_ci95']:.3f}"
    json.dump(out, open(os.path.join(ROOT, "results", "aa_summary.json"), "w"), indent=1)
    os.makedirs(os.path.join(ROOT, "paper"), exist_ok=True)
    with open(os.path.join(ROOT, "paper", "numbers_aa.tex"), "w") as fh:
        fh.write("% generated by experiments/aa_summary.py\n")
        for k, v in macros.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
