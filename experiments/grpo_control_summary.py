"""GRPO against a scripted rival that punishes (results/grpo/trig_*): share of
periods in which the policy is punished, averaged over the last ten training
iterations, with forward-looking (gamma 0.9) and myopic (gamma 0) credit.
Writes paper/numbers_grpoctrl.tex.

    python experiments/grpo_control_summary.py
"""
from __future__ import annotations

import glob
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
LAST = 10


def main():
    shares = {"Fwd": [], "Myo": []}
    for d in sorted(glob.glob(os.path.join(ROOT, "results", "grpo", "trig_*"))):
        f = os.path.join(d, "log.jsonl")
        if not os.path.isdir(d) or not os.path.exists(f):
            continue
        rows = [json.loads(l) for l in open(f) if l.strip()]
        s = [r["punished_share"] for r in rows if "punished_share" in r][-LAST:]
        key = "Myo" if "_g0" in os.path.basename(d) and "_g09" not in os.path.basename(d) else "Fwd"
        shares[key].append(100 * sum(s) / len(s))
        print(os.path.basename(d), key, f"{shares[key][-1]:.2f}%")
    with open(os.path.join(ROOT, "paper", "numbers_grpoctrl.tex"), "w") as fh:
        fh.write("% generated by experiments/grpo_control_summary.py\n")
        for k, v in shares.items():
            fh.write(f"\\newcommand{{\\GrpoCtrl{k}Min}}{{{min(v):.1f}}}\n")
            fh.write(f"\\newcommand{{\\GrpoCtrl{k}Max}}{{{max(v):.1f}}}\n")


if __name__ == "__main__":
    main()
