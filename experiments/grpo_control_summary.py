"""GRPO against a scripted rival that punishes (results/grpo/trig_*): share of
periods in which the policy is punished, averaged over the last ten training
iterations, with forward-looking (gamma 0.9) and myopic (gamma 0) credit.
Writes paper/numbers_grpoctrl.tex.

    python experiments/grpo_control_summary.py
"""
from __future__ import annotations

import glob
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
LAST = 10


def main():
    shares = {"Fwd": [], "Myo": []}
    for d in sorted(glob.glob(os.path.join(ROOT, "results", "grpo", "trig_*"))):
        f = os.path.join(d, "log.jsonl")
        if not os.path.isdir(d) or not os.path.exists(f):
            continue
        rows = [json.loads(l) for l in open(f) if l.strip()]
        s = [r["punished_share"] for r in rows if "punished_share" in r][-LAST:]
        key = "Myo" if "_g0" in os.path.basename(d) and "_g09" not in os.path.basename(d) else "Fwd"
        shares[key].append(100 * sum(s) / len(s))
        print(os.path.basename(d), key, f"{shares[key][-1]:.2f}%")
    # the trained policies paired with themselves, with the rival's orders shown as in training
    import numpy as np
    from scipy import stats
    pair = {}
    for key, run in (("Fwd", "trig_0p6b_su1_g09"), ("Myo", "trig_0p6b_su1_g0")):
        fs = sorted(glob.glob(os.path.join(ROOT, "results", "grpo_audit", f"{run}_adapter_*_monitor.json")))
        fs = [f for f in fs if os.path.getsize(f) > 0]
        if not fs:
            continue
        d = json.load(open(fs[-1]))
        fb = d["bench_fixed"]
        b = np.asarray(d["per_session"]["agg_intensity"], float)
        delta = (b - fb["agg_nash"]) / (fb["agg_coll"] - fb["agg_nash"])
        tq = stats.t.ppf(0.975, len(delta) - 1)
        r = {"delta": (float(delta.mean()), float(tq * delta.std(ddof=1) / np.sqrt(len(delta))))}
        for test, tag in (("deviation", "BR"), ("deviation_shift", "Shift")):
            dv = d.get(test)
            if dv:
                r[tag] = (dv["d_beta_rival"][1], dv["d_beta_rival_ci95"][1], dv["cum_gain_dev"], dv["cum_gain_dev_ci95"])
        pair[key] = r
        print(run, r)
    os.makedirs(os.path.join(ROOT, "paper"), exist_ok=True)
    with open(os.path.join(ROOT, "paper", "numbers_grpoctrl.tex"), "w") as fh:
        fh.write("% generated by experiments/grpo_control_summary.py\n")
        for k, v in shares.items():
            fh.write(f"\\newcommand{{\\GrpoCtrl{k}Min}}{{{min(v):.1f}}}\n")
            fh.write(f"\\newcommand{{\\GrpoCtrl{k}Max}}{{{max(v):.1f}}}\n")
        for k in ("Fwd", "Myo"):
            r = pair.get(k, {})
            m = {"PairDelta": f"{r['delta'][0]:.2f}" if "delta" in r else "--"}
            for tag in ("BR", "Shift"):
                v = r.get(tag)
                m[f"Pair{tag}"] = f"{v[0]:.2f}\\pm{v[1]:.2f}" if v else "--"
                m[f"Pair{tag}Gain"] = f"{v[2]:+.2f}\\pm{v[3]:.2f}" if v else "--"
            for f, v in m.items():
                fh.write(f"\\newcommand{{\\GrpoCtrl{k}{f}}}{{{v}}}\n")


if __name__ == "__main__":
    main()
